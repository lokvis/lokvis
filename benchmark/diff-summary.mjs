/**
 * Benchmark PR 正文生成器(D4)—— 对比 knowledge data/benchmarks/ 中
 * 最新与上期 image-ops 报告,输出关键指标变化百分比的 markdown 摘要。
 *
 * 用法:node diff-summary.mjs <benchmarks-dir>  (输出到 stdout)
 */
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node diff-summary.mjs <benchmarks-dir>');
  process.exit(1);
}

const files = readdirSync(dir)
  .filter((f) => /^image-ops-\d{4}-\d{2}\.json$/.test(f))
  .sort();

const latest = JSON.parse(readFileSync(join(dir, files[files.length - 1]), 'utf8'));

const caseKey = (r) => `${r.operation} ${r.from.slice(7)}->${r.to.slice(7)} q${r.quality}`;

const pct = (prev, cur) => {
  if (prev == null || cur == null || prev === 0) return '—';
  const d = ((cur - prev) / prev) * 100;
  return `${d >= 0 ? '+' : ''}${d.toFixed(1)}%`;
};

const lines = [];
lines.push('## Monthly image benchmark (automated)');
lines.push('');
lines.push(`- **id**: \`${latest.id}\``);
lines.push(`- **runner**: ${latest.runner.engine}@${latest.runner.engineVersion} / ${latest.runner.environment} / ${latest.runner.hardwareClass}`);
lines.push(`- **corpus**: ${latest.corpus.name} (${latest.corpus.imageCount} images, \`${latest.corpus.sourceRef}\`)`);
lines.push(`- **results**: ${latest.results.length} combinations`);
lines.push('');

if (files.length < 2) {
  lines.push('First benchmark record — no previous period to diff against.');
} else {
  const prev = JSON.parse(readFileSync(join(dir, files[files.length - 2]), 'utf8'));
  const prevByKey = new Map(prev.results.map((r) => [caseKey(r), r]));
  lines.push(`### Diff vs \`${prev.id}\``);
  lines.push('');
  lines.push('| case | encodeMs | Δ | bytesRatio | Δ | ssim | Δ |');
  lines.push('|---|---|---|---|---|---|---|');
  for (const r of latest.results) {
    const p = prevByKey.get(caseKey(r));
    lines.push(
      `| ${caseKey(r)} | ${r.metrics.encodeMsMedian} | ${pct(p?.metrics.encodeMsMedian, r.metrics.encodeMsMedian)} | ${r.metrics.bytesRatioMedian} | ${pct(p?.metrics.bytesRatioMedian, r.metrics.bytesRatioMedian)} | ${r.metrics.ssimMean ?? '—'} | ${pct(p?.metrics.ssimMean, r.metrics.ssimMean)} |`
    );
  }
  const removed = prev.results.filter((r) => !latest.results.some((l) => caseKey(l) === caseKey(r)));
  if (removed.length) {
    lines.push('');
    lines.push(`Combinations present last period but missing now: ${removed.map(caseKey).join(', ')}`);
  }
}

lines.push('');
lines.push('---');
lines.push('Generated by `lokvis-open/.github/workflows/benchmark.yml`. Review checklist: compression ratio direction sane (e.g. png->webp < 1), encodeMs magnitude plausible, runner metadata reproducible.');

console.log(lines.join('\n'));
